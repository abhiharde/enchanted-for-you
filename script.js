function selectBackground(images, storageKey, cssProperty) {
  let previousImage = "";
  try { previousImage = localStorage.getItem(storageKey) || ""; } catch {}
  const choices = images.filter((image) => image !== previousImage);
  const availableImages = choices.length ? choices : images;
  const image = availableImages[Math.floor(Math.random() * availableImages.length)];
  document.documentElement.style.setProperty(cssProperty, `url("${image}")`);
  try { localStorage.setItem(storageKey, image); } catch {}
}

