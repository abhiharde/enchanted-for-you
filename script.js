let galleryTimer;
let activeGalleryImage = "a";
function startGallery() {
  const imagePaths = CONFIG.galleryImages;
  clearInterval(galleryTimer);
  if (!imagePaths.length) return;

  const imageA = $("gallery-image-a");
  const imageB = $("gallery-image-b");
  let currentIndex = Math.floor(Math.random() * imagePaths.length);
  imageA.src = imagePaths[currentIndex];
  imageA.classList.add("is-visible");
  imageB.classList.remove("is-visible");
  activeGalleryImage = "a";
  $("gallery-empty").hidden = true;
  $("gallery-stage").hidden = false;

  if (imagePaths.length < 2) return;
  galleryTimer = setInterval(() => {
    const choices = imagePaths.map((_, index) => index).filter((index) => index !== currentIndex);
    const nextIndex = choices[Math.floor(Math.random() * choices.length)];
    const incoming = activeGalleryImage === "a" ? imageB : imageA;
    const outgoing = activeGalleryImage === "a" ? imageA : imageB;
    const preload = new Image();
    preload.onload = () => {
      incoming.src = imagePaths[nextIndex];
      incoming.alt = `Memory ${nextIndex + 1}`;
      requestAnimationFrame(() => {
        incoming.classList.add("is-visible");
        outgoing.classList.remove("is-visible");
        activeGalleryImage = activeGalleryImage === "a" ? "b" : "a";
        currentIndex = nextIndex;
      });
    };
    preload.src = imagePaths[nextIndex];
  }, 4000);
}

$("gallery-button").onclick = () => { startGallery(); $("gallery-dialog").showModal(); };
